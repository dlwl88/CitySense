import static com.hmdp.utils.RedisConstants.FEED_KEY;

/**
 * <p>
 * 服务实现类
 * </p>
 *
 */
@Service
public class BlogServiceImpl extends ServiceImpl<BlogMapper, Blog> implements IBlogService {

    @Resource
    private IUserService userService;

    @Resource
    private StringRedisTemplate stringRedisTemplate;

    @Resource
    private IFollowService followService;

    @Resource
    private RedissonClient redissonClient;

    private static final DefaultRedisScript<Long> BLOG_LIKE_SCRIPT;
    static {
        BLOG_LIKE_SCRIPT = new DefaultRedisScript<>();
        BLOG_LIKE_SCRIPT.setLocation(new ClassPathResource("blog_like.lua"));
        BLOG_LIKE_SCRIPT.setResultType(Long.class);
    }

    @Override
    public Result queryHotBlog(Integer current) {
        // 根据用户查询
        Page<Blog> page = query()
                .orderByDesc("liked")
                .page(new Page<>(current, SystemConstants.MAX_PAGE_SIZE));
        // 获取当前页数据
        List<Blog> records = page.getRecords();
        fillLikeCounts(records);
        // 查询用户
        records.forEach(blog -> {
            this.queryBlogUser(blog);
            this.isBlogLiked(blog);
        });
        return Result.ok(records);
    }

    @Override
    public Result queryBlogById(Long id) {
        // 1.查询blog
        Blog blog = getById(id);
        if (blog == null) {
            return Result.fail("笔记不存在！");
        }
        fillLikeCounts(List.of(blog));
        // 2.查询blog有关的用户
        queryBlogUser(blog);
        // 3.查询blog是否被点赞
        isBlogLiked(blog);
        return Result.ok(blog);
    }

    private void isBlogLiked(Blog blog) {
        // 1.获取登录用户
        UserDTO user = UserHolder.getUser();
        if (user == null) {
            // 用户未登录，无需查询是否点赞
            return;
        }
        Long userId = user.getId();
        // 2.判断当前登录用户是否已经点赞
        String key = BLOG_LIKED_KEY + blog.getId();
        Double score = stringRedisTemplate.opsForZSet().score(key, userId.toString());
        blog.setIsLike(score != null);
    }

    @Override
    public Result likeBlog(Long id) {
        Long userId = UserHolder.getUser().getId();
        Long result = executeLikeScript(id, userId);
        if (Long.valueOf(-1).equals(result)) {
            if (!initializeLikeMeta(id)) {
                return Result.fail("笔记不存在！");
            }
            result = executeLikeScript(id, userId);
        }
        if (result == null || result < 0) {
            return Result.fail("点赞计数异常，请稍后重试");
        }
        return Result.ok();
    }

    private Long executeLikeScript(Long blogId, Long userId) {
        return stringRedisTemplate.execute(BLOG_LIKE_SCRIPT,
                List.of(BLOG_LIKED_KEY + blogId, BLOG_LIKE_META_KEY + blogId, BLOG_LIKE_DIRTY_KEY),
                userId.toString(), blogId.toString(), Long.toString(System.currentTimeMillis()));
    }

    private boolean initializeLikeMeta(Long id) {
        String key = BLOG_LIKE_META_KEY + id;
        RLock lock = redissonClient.getLock("lock:blog:like:init:" + id);
        lock.lock();
        try {
            Map<Object, Object> meta = stringRedisTemplate.opsForHash().entries(key);
            if (meta.containsKey("count") && meta.containsKey("version")) {
                return true;
            }
            if (!meta.isEmpty() || Boolean.TRUE.equals(stringRedisTemplate.opsForHash()
                    .hasKey(BLOG_LIKE_DIRTY_KEY, id.toString()))) {
                throw new IllegalStateException("点赞 Redis 数据不完整，需要恢复，blogId=" + id);
            }
            Blog blog = query().select("id", "liked", "like_version").eq("id", id).one();
            if (blog == null) return false;
            // 历史总数以数据库为基线，不能用不完整的 ZSet 数量替代。
            stringRedisTemplate.opsForHash().putAll(key, Map.of(
                    "count", Integer.toString(blog.getLiked() == null ? 0 : blog.getLiked()),
                    "version", Long.toString(blog.getLikeVersion())));
            return true;
        } finally {
            if (lock.isHeldByCurrentThread()) lock.unlock();
        }
    }

    @Override
    public void fillLikeCounts(List<Blog> blogs) {
        if (blogs.isEmpty()) return;
        byte[] field = "count".getBytes(StandardCharsets.UTF_8);
        List<Object> counts = stringRedisTemplate.executePipelined((RedisCallback<Object>) connection -> {
            for (Blog blog : blogs) {
                connection.hashCommands().hGet(
                        (BLOG_LIKE_META_KEY + blog.getId()).getBytes(StandardCharsets.UTF_8), field);
            }
            return null;
        });
        for (int i = 0; i < blogs.size(); i++) {
            if (counts.get(i) != null) {
                blogs.get(i).setLiked(Integer.parseInt(counts.get(i).toString()));
            }
        }
    }

    @Override
    public Result queryBlogLikes(Long id) {
        String key = BLOG_LIKED_KEY + id;
        // 1.查询top5的点赞用户 zrange key 0 4
        Set<String> top5 = stringRedisTemplate.opsForZSet().range(key, 0, 4);
        if (top5 == null || top5.isEmpty()) {
            return Result.ok(Collections.emptyList());
        }
        // 2.解析出其中的用户id
        List<Long> ids = top5.stream().map(Long::valueOf).collect(Collectors.toList());
        String idStr = StrUtil.join(",", ids);
        // 3.根据用户id查询用户 WHERE id IN ( 5 , 1 ) ORDER BY FIELD(id, 5, 1)
        List<UserDTO> userDTOS = userService.query()
                .in("id", ids).last("ORDER BY FIELD(id," + idStr + ")").list()
                .stream()
                .map(user -> BeanUtil.copyProperties(user, UserDTO.class))
                .collect(Collectors.toList());
        // 4.返回
        return Result.ok(userDTOS);
    }

    @Override
    public Result saveBlog(Blog blog) {
        // 1.获取登录用户
        UserDTO user = UserHolder.getUser();
        blog.setUserId(user.getId());
        // 2.保存探店笔记
        boolean isSuccess = save(blog);
        if(!isSuccess){
            return Result.fail("新增笔记失败!");
        }
        // 3.查询笔记作者的所有粉丝 select * from tb_follow where follow_user_id = ?
        List<Follow> follows = followService.query().eq("follow_user_id", user.getId()).list();
        // 4.推送笔记id给所有粉丝
        for (Follow follow : follows) {
            // 4.1.获取粉丝id
            Long userId = follow.getUserId();
            // 4.2.推送
            String key = FEED_KEY + userId;
            stringRedisTemplate.opsForZSet().add(key, blog.getId().toString(), System.currentTimeMillis());
        }
        // 5.返回id
        return Result.ok(blog.getId());
    }

    @Override
    public Result queryBlogOfFollow(Long max, Integer offset) {
        // 1.获取当前用户
        Long userId = UserHolder.getUser().getId();
        // 2.查询收件箱 ZREVRANGEBYSCORE key Max Min LIMIT offset count
        String key = FEED_KEY + userId;
        Set<ZSetOperations.TypedTuple<String>> typedTuples = stringRedisTemplate.opsForZSet()
                .reverseRangeByScoreWithScores(key, 0, max, offset, 2);
        // 3.非空判断
        if (typedTuples == null || typedTuples.isEmpty()) {
            return Result.ok();
        }
        // 4.解析数据：blogId、minTime（时间戳）、offset
        List<Long> ids = new ArrayList<>(typedTuples.size());
        long minTime = 0; // 2
        int os = 1; // 2
        for (ZSetOperations.TypedTuple<String> tuple : typedTuples) { // 5 4 4 2 2
            // 4.1.获取id
            ids.add(Long.valueOf(tuple.getValue()));
            // 4.2.获取分数(时间戳）
            long time = tuple.getScore().longValue();
            if(time == minTime){
                os++;
            }else{
                minTime = time;
                os = 1;
            }
        }

        // 5.根据id查询blog
        String idStr = StrUtil.join(",", ids);
        List<Blog> blogs = query().in("id", ids).last("ORDER BY FIELD(id," + idStr + ")").list();
        fillLikeCounts(blogs);

        for (Blog blog : blogs) {
            // 5.1.查询blog有关的用户
            queryBlogUser(blog);
            // 5.2.查询blog是否被点赞
            isBlogLiked(blog);
        }

        // 6.封装并返回
        ScrollResult r = new ScrollResult();
        r.setList(blogs);
        r.setOffset(os);
        r.setMinTime(minTime);

        return Result.ok(r);
    }

    private void queryBlogUser(Blog blog) {
        Long userId = blog.getUserId();
        User user = userService.getById(userId);
        blog.setName(user.getNickName());
        blog.setIcon(user.getIcon());
    }
}
